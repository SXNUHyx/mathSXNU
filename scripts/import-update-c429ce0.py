def main():
    parser = argparse.ArgumentParser(description='MathSig c429ce0 离线更新，保留原Git历史和本地配置')
    parser.add_argument('--project', default='/opt/mathsxnu')
    parser.add_argument('--check', action='store_true', help='只检查，不导入代码')
    args = parser.parse_args()
    project = Path(args.project).resolve()

    def git(*params):
        return subprocess.check_output(['git', '-C', str(project), *params]).decode().strip()

    if Path(git('rev-parse', '--show-toplevel')).resolve() != project:
        raise SystemExit('不是项目根目录，已停止。')
    current = git('rev-parse', 'HEAD')
    if git('status', '--porcelain'):
        raise SystemExit('存在本地改动，已停止；请先备份并核对，不要强制覆盖。')
    if current == TARGET:
        print('已是 c429ce0，Git状态干净，无需再次导入。')
        return
    if current not in BASES:
        raise SystemExit('当前版本不适用此工具：'+current+'；已停止。')
    payload = base64.b64decode(PAYLOAD)
    if hashlib.sha256(payload).hexdigest() != PAYLOAD_SHA256:
        raise SystemExit('更新数据校验失败，已停止。')
    with tempfile.TemporaryDirectory(prefix='mathsig-c429ce0-') as tmp:
        bundle = Path(tmp) / 'update.bundle'
        bundle.write_bytes(payload)
        subprocess.run(['git', '-C', str(project), 'bundle', 'verify', str(bundle)], check=True)
        if args.check:
            print('检查通过：可从 '+current[:7]+' 离线更新至 c429ce0；尚未修改代码。')
            return
        subprocess.run(['git', '-C', str(project), 'fetch', str(bundle), 'HEAD'], check=True)
        if git('rev-parse', 'FETCH_HEAD') != TARGET:
            raise SystemExit('目标提交不匹配，未合并。')
        subprocess.run(['git', '-C', str(project), 'merge', '--ff-only', TARGET], check=True)
    if git('rev-parse', 'HEAD') != TARGET or git('status', '--porcelain'):
        raise SystemExit('导入后的版本或Git状态异常，请保留输出检查。')
    print('离线代码更新完成：c429ce0。请继续原目录的Docker构建、二次备份及重启。')


if __name__ == '__main__':
    main()
